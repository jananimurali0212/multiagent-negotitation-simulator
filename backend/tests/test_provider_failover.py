@pytest.mark.asyncio
async def test_negotiation_state_remains_unchanged_during_failover(caplog):
    primary_quota = MockFailingProvider("gemini", is_quota=True)
    groq_success = MockSuccessProvider("groq")
    manager = LLMProviderManager(providers=[primary_quota, groq_success])

    engine = LangGraphNegotiationEngine(provider_manager=manager)

    state: NegotiationState = {
        "session_id": "sess-state-preserve-test",
        "scenario_id": "vendor-pricing",
        "mode": "ai-ai",
        "current_round": 2,
        "max_rounds": 10,
        "current_speaker_index": 1,
        "current_turn_speaker": "Procurement Lead",
        "agents": [
            {
                "id": "agent-1",
                "name": "Vendor VP",
                "role": "Sales VP",
                "avatar": "VP",
                "personality": "Aggressive",
                "goals": [],
                "constraints": [],
            },
            {
                "id": "agent-2",
                "name": "Procurement Lead",
                "role": "Procurement Lead",
                "avatar": "PL",
                "personality": "Collaborative",
                "goals": [],
                "constraints": [],
            },
        ],
        "messages": [
            {"sender": "Vendor VP", "role": "Sales VP", "content": "Initial price is $70/mo", "offer_data": {"price": "$70/user/month"}}
        ],
        "current_offer": {"price": "$70/user/month"},
        "agreement_reached": False,
        "deadlock_detected": False,
        "status": "running",
        "latest_decision": None,
    }

    res = await engine.agent_reasoning_node(state)

    # State parameters preserved correctly (speaker 1 completes turn -> speaker 0 is next -> round advances to 3)
    assert res["current_round"] == 3
    assert len(res["messages"]) == 2
    assert res["messages"][1]["sender"] == "Procurement Lead"
    assert res["latest_decision"]["action"] == "counteroffer"
