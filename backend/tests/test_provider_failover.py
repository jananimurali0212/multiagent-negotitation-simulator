class MockFailingProvider(BaseLLMProvider):
    def __init__(self, name: str, is_quota: bool = False, is_transient: bool = True):
        self._name = name
        self.is_quota = is_quota
        self.is_transient = is_transient
        self.call_count = 0

    def provider_name(self) -> str:
        return self._name

    def supports_structured_output(self) -> bool:
        return True

    async def health_check(self) -> bool:
        return True

    async def generate_decision(
        self, prompt: str, agent_personality: str, agent_role: str, current_round: int, scenario_id: str, *args, **kwargs
    ) -> AgentDecision:
        self.call_count += 1
        raise LLMProviderError(
            message=f"Simulated failure for {self._name}",
            provider_name=self._name,
            status_code=429 if self.is_quota else 500,
            is_quota=self.is_quota,
            is_transient=self.is_transient,
        )


class MockSuccessProvider(BaseLLMProvider):
    def __init__(self, name: str):
        self._name = name
        self.call_count = 0

    def provider_name(self) -> str:
        return self._name

    def supports_structured_output(self) -> bool:
        return True

    async def health_check(self) -> bool:
        return True

    async def generate_decision(
        self, prompt: str, agent_personality: str, agent_role: str, current_round: int, scenario_id: str, *args, **kwargs
    ) -> AgentDecision:
        self.call_count += 1
        return AgentDecision(
            action="counteroffer",
            message=f"Proposal from {self._name}",
            rationale_summary=f"Generated by {self._name}",
            offer={"price": "$50/user/month"},
            concession_percentage=5.0,
            confidence_score=0.95,
        )


@pytest.mark.asyncio
async def test_primary_provider_success():
    primary = MockSuccessProvider("gemini")
    fallback = FallbackRuleProvider()
    manager = LLMProviderManager(providers=[primary, fallback])

    decision = await manager.generate_decision(
        prompt="Test prompt",
        agent_personality="Analytical",
        agent_role="Vendor Sales Director",
        current_round=1,
        scenario_id="vendor-pricing",
        session_id="test-session-123",
    )

    assert isinstance(decision, AgentDecision)
    assert decision.message == "Proposal from gemini"
    assert decision.offer == {"price": "$50/user/month"}


